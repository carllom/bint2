describe('announceByteOrder — the byte-order flip message (#55, plan §4.3)', () => {
  it('sets the action-status slot with the spelled-out order', () => {
    const store = useDocumentStore()
    store.announceByteOrder('le')
    expect(store.actionStatus).toMatchObject({ ok: true, message: 'Byte order: little-endian' })
    store.announceByteOrder('be')
    expect(store.actionStatus).toMatchObject({ ok: true, message: 'Byte order: big-endian' })
  })

  it('is sticky — a Selection move does not clear it, only the next action (plan §4.4)', () => {
    const store = useDocumentStore()
    store.open(sourceOfSize(64), 'a.bin')
    store.setCursor(4)
    store.announceByteOrder('be')

    store.setCursor(8) // the copy path's clear does not touch a sticky message
    expect(store.actionStatus?.message).toBe('Byte order: big-endian')

    // The next copy replaces it, and that message *is* cleared on a later move.
    store.setCursor(12)
    store.extendSelectionTo(15)
    store.actionStatus = { ok: true, message: 'Copied 4 bytes to the clipboard as hex.' }
    store.setCursor(20)
    expect(store.actionStatus).toBeNull()
  })
})

describe('sourceHealth — the dead-source banner state (#26, ADR-0004)', () => {
  it('defaults to ok and resets to ok on open', () => {
    const store = useDocumentStore()
    expect(store.sourceHealth).toBe('ok')

    store.open(sourceOfSize(64), 'a.bin')
    store.setSourceHealth('failing')
    expect(store.sourceHealth).toBe('failing')

    store.open(sourceOfSize(64), 'b.bin')
    expect(store.sourceHealth).toBe('ok')
  })

  it('takes ok and failing transitions freely', () => {
    const store = useDocumentStore()
    store.open(sourceOfSize(64), 'a.bin')

    store.setSourceHealth('failing')
    expect(store.sourceHealth).toBe('failing')
    store.setSourceHealth('ok')
    expect(store.sourceHealth).toBe('ok')
  })

  it('latches gone: neither a later read-failed escalation nor a stray success can move away from it, only open', () => {
    const store = useDocumentStore()
    store.open(sourceOfSize(64), 'a.bin')

    store.setSourceHealth('gone')
    expect(store.sourceHealth).toBe('gone')

    // A read-failed rejection settling after the one that latched — e.g. a
    // different row's fetch, in the same batch, resolving in a different
    // order — must not downgrade the banner to the escalation wording.
    store.setSourceHealth('failing')
    expect(store.sourceHealth).toBe('gone')

    // Nor can a stray success dismiss it entirely.
    store.setSourceHealth('ok')
    expect(store.sourceHealth).toBe('gone')

    // Only opening a new document resets it.
    store.open(sourceOfSize(64), 'b.bin')
    expect(store.sourceHealth).toBe('ok')
  })
})

describe('requestReveal — the Bitmap click-to-cursor reveal signal (plan §4.9)', () => {
  it('is null until a reveal is asked for', () => {
    expect(useDocumentStore().revealRequest).toBeNull()
  })

  it('carries the (byte-clamped) offset in a fresh object each call — a repeat is still a distinct trigger', () => {
    const store = useDocumentStore()
    store.open(sourceOfSize(4096), 'a.bin')

    store.requestReveal(1000)
    expect(store.revealRequest).toEqual({ offset: 1000 })
    const first = store.revealRequest

    store.requestReveal(1000)
    expect(store.revealRequest).toEqual({ offset: 1000 })
    expect(store.revealRequest).not.toBe(first) // a new reference, so the watcher re-fires

    store.requestReveal(999_999) // clamped to the last real byte
    expect(store.revealRequest!.offset).toBe(4095)
  })

  it('is inert with no document open, and resets when one opens', () => {
    const store = useDocumentStore()
    store.requestReveal(10)
    expect(store.revealRequest).toBeNull()

    store.open(sourceOfSize(4096), 'a.bin')
    store.requestReveal(10)
    expect(store.revealRequest).not.toBeNull()

    store.open(sourceOfSize(2048), 'b.bin')
    expect(store.revealRequest).toBeNull()
  })
})

describe('derivedWorkClient — the worker-crossing lifecycle (#103, ADR-0013)', () => {
  it('is null until a document opens with one', () => {
    expect(useDocumentStore().derivedWorkClient).toBeNull()
  })

  it('open with no third argument leaves it null — every existing call site is unaffected', () => {
    const store = useDocumentStore()
    store.open(sourceOfSize(64), 'a.bin')
    expect(store.derivedWorkClient).toBeNull()
  })

  it('holds the client a caller passes to open', () => {
    const store = useDocumentStore()
    const { client } = derivedWorkClient()
    store.open(sourceOfSize(64), 'a.bin', client)
    expect(store.derivedWorkClient).toBe(client)
  })

  it('terminates the previous document’s client when the next document opens — one worker per open document', () => {
    const store = useDocumentStore()
    const first = derivedWorkClient()
    const second = derivedWorkClient()
    store.open(sourceOfSize(64), 'a.bin', first.client)

    store.open(sourceOfSize(64), 'b.bin', second.client)

    expect(first.worker.terminateCalls).toBe(1)
    expect(store.derivedWorkClient).toBe(second.client)
  })

  it('opening a plain document (no client) still terminates the previous one', () => {
    const store = useDocumentStore()
    const first = derivedWorkClient()
    store.open(sourceOfSize(64), 'a.bin', first.client)

    store.open(sourceOfSize(64), 'b.bin')

    expect(first.worker.terminateCalls).toBe(1)
    expect(store.derivedWorkClient).toBeNull()
  })
})
