/** A hand-driven fake of the worker seam (mirrors `DerivedWorkClient.spec.ts`) —
 *  enough to construct a real `DerivedWorkClient` without a real `Worker`. */
class FakeWorker implements DerivedWorkWorkerLike {
  onmessage: ((event: MessageEvent) => void) | null = null
  terminateCalls = 0
  postMessage(): void {}
  terminate(): void {
    this.terminateCalls++
  }
}

function derivedWorkClient(): { client: DerivedWorkClient; worker: FakeWorker } {
  const worker = new FakeWorker()
  const client = new DerivedWorkClient(new File([], 'x.bin'), { createWorker: () => worker })
  return { client, worker }
}

/** A bytes-only stub — the store never reads, it only tracks identity and size. */
function sourceOfSize(size: number): ByteSource {
  return {
    size,
    read: () => Promise.resolve(new Uint8Array()),
    readSync: () => null,
    prefetch: () => {},
    close: () => {},
  }
}

/** Byte `i` holds `i & 0xff`, generated on demand — never allocated whole. */
function generated(offset: number, length: number, size: number): Uint8Array {
  const count = Math.max(0, Math.min(length, size - offset))
  const bytes = new Uint8Array(count)
  for (let i = 0; i < count; i++) {
    bytes[i] = (offset + i) & 0xff
  }
  return bytes
}

/**
 * A source that serves generated bytes through `read` and records every call, so
 * a test can prove the copy takes its bytes in one shot (a Direct read past the
 * cache threshold), never chunked. `readSync` always misses.
 */
class RecordingSource implements ByteSource {
  readonly reads: { offset: number; length: number }[] = []
  constructor(readonly size: number) {}
  read(offset: number, length: number): Promise<Uint8Array> {
    this.reads.push({ offset, length })
    return Promise.resolve(generated(offset, length, this.size))
  }
  readSync(): Uint8Array | null {
    return null
  }
  prefetch(): void {}
  close(): void {}
}

/**
 * A dead source: `read` always rejects, but `readSync` still answers for bytes
 * that were resident when it died — the emergent behaviour ADR-0004 leans on.
 */
class DeadButResidentSource implements ByteSource {
  constructor(
    readonly size: number,
    private readonly residentEnd: number,
  ) {}
  read(): Promise<Uint8Array> {
    return Promise.reject(new Error('source-gone'))
  }
  readSync(offset: number, length: number): Uint8Array | null {
    return offset + length <= this.residentEnd ? generated(offset, length, this.size) : null
  }
  prefetch(): void {}
  close(): void {}
}

